import { randomUUID } from 'node:crypto';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { DeleteObjectCommand, DeleteObjectsCommand, ListObjectsV2Command, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';
import { env } from '../config/env.js';

/**
 * File storage behind a tiny interface, so the services never know where photos live.
 *   local — files on this server's disk, served at /uploads (development, tests)
 *   s3    — any S3-compatible bucket: Supabase Storage, Backblaze B2, Cloudflare R2 (production: hosting disks are wiped on deploy)
 *
 * Keys look like "users/<userId>/<uuid>.jpg". Local URLs are returned *relative* ("/uploads/<key>"):
 * the app prefixes them with the API host it is talking to, which keeps links working through
 * tunnels. Bucket URLs are absolute (the bucket's public domain).
 */
export interface Storage {
  save(prefix: string, data: Buffer, ext: string): Promise<string>;
  remove(key: string): Promise<void>;
  removePrefix(prefix: string): Promise<void>;
  url(key: string): string;
}

const CONTENT_TYPE: Record<string, string> = { jpg: 'image/jpeg', png: 'image/png', webp: 'image/webp' };
// Seeded demo photos are absolute URLs; they pass through untouched.
const isAbsolute = (key: string) => /^https?:\/\//.test(key);

export function diskStorage(root: string): Storage {
  // Keys are generated by us, but never trust them blindly when touching the disk.
  const safePath = (key: string) => {
    const full = path.resolve(root, key);
    if (!full.startsWith(root + path.sep)) throw new Error('Invalid storage key');
    return full;
  };
  return {
    async save(prefix, data, ext) {
      const key = `${prefix}/${randomUUID()}.${ext}`;
      const full = safePath(key);
      await mkdir(path.dirname(full), { recursive: true });
      await writeFile(full, data);
      return key;
    },
    async remove(key) {
      await rm(safePath(key), { force: true });
    },
    async removePrefix(prefix) {
      await rm(safePath(prefix), { recursive: true, force: true });
    },
    url(key) {
      return isAbsolute(key) ? key : `/uploads/${key}`;
    },
  };
}

/** The part of S3Client this driver uses, so tests can pass a fake. */
export type S3Like = Pick<S3Client, 'send'>;

export function bucketStorage(client: S3Like, bucket: string, publicUrl: string): Storage {
  const base = publicUrl.replace(/\/+$/, '');
  return {
    async save(prefix, data, ext) {
      const key = `${prefix}/${randomUUID()}.${ext}`;
      await client.send(
        new PutObjectCommand({
          Bucket: bucket,
          Key: key,
          Body: data,
          ContentType: CONTENT_TYPE[ext] ?? 'application/octet-stream',
          // File names are random and never reused, so caches may keep them forever.
          CacheControl: 'public, max-age=31536000, immutable',
        }),
      );
      return key;
    },
    async remove(key) {
      if (isAbsolute(key)) return;
      await client.send(new DeleteObjectCommand({ Bucket: bucket, Key: key }));
    },
    async removePrefix(prefix) {
      // Lists 1000 keys at a time and deletes each page in one request.
      let token: string | undefined;
      do {
        const page = await client.send(
          new ListObjectsV2Command({ Bucket: bucket, Prefix: `${prefix.replace(/\/+$/, '')}/`, ContinuationToken: token }),
        );
        const keys = (page.Contents ?? []).flatMap((o) => (o.Key ? [{ Key: o.Key }] : []));
        if (keys.length) await client.send(new DeleteObjectsCommand({ Bucket: bucket, Delete: { Objects: keys, Quiet: true } }));
        token = page.IsTruncated ? page.NextContinuationToken : undefined;
      } while (token);
    },
    url(key) {
      return isAbsolute(key) ? key : `${base}/${key}`;
    },
  };
}

export const uploadRoot = path.resolve(env.UPLOAD_DIR);

export const storage: Storage =
  env.STORAGE_DRIVER === 's3'
    ? bucketStorage(
        new S3Client({
          region: env.S3_REGION,
          endpoint: env.S3_ENDPOINT,
          forcePathStyle: env.S3_FORCE_PATH_STYLE,
          credentials: { accessKeyId: env.S3_ACCESS_KEY_ID, secretAccessKey: env.S3_SECRET_ACCESS_KEY },
        }),
        env.S3_BUCKET,
        env.S3_PUBLIC_URL,
      )
    : diskStorage(uploadRoot);
