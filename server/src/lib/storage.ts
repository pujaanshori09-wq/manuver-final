import { randomUUID } from 'node:crypto';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { env } from '../config/env.js';

/**
 * File storage behind a tiny interface so the local-disk driver can be swapped for
 * S3 / Cloudflare R2 at deploy time without touching the services.
 *
 * Keys look like "users/<userId>/<uuid>.jpg". Public URLs are returned *relative*
 * ("/uploads/<key>"): the app prefixes them with the API host it is talking to, which
 * keeps links working through tunnels and proxies.
 */
export interface Storage {
  save(prefix: string, data: Buffer, ext: string): Promise<string>;
  remove(key: string): Promise<void>;
  removePrefix(prefix: string): Promise<void>;
  url(key: string): string;
}

const root = path.resolve(env.UPLOAD_DIR);

// Keys are generated by us, but never trust them blindly when touching the disk.
function safePath(key: string) {
  const full = path.resolve(root, key);
  if (!full.startsWith(root + path.sep)) throw new Error('Invalid storage key');
  return full;
}

export const storage: Storage = {
  async save(prefix, data, ext) {
    const key = `${prefix}/${randomUUID()}.${ext}`;
    const full = safePath(key);
    await mkdir(path.dirname(full), { recursive: true });
    await writeFile(full, data);
    return key;
  },
  async remove(key) {
    await rm(safePath(key), { force: true });
  },
  async removePrefix(prefix) {
    await rm(safePath(prefix), { recursive: true, force: true });
  },
  url(key) {
    // Seeded demo photos are absolute URLs; real uploads are keys served under /uploads.
    if (/^https?:\/\//.test(key)) return key;
    return `/uploads/${key}`;
  },
};

export const uploadRoot = root;
